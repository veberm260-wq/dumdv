ITEM = re.compile(r'<div class="region-item"[^>]*>(.*?)</div>\s*</div>', re.S)
CODE = re.compile(r'data-region-url="https://domvrayu\.ru/(\d+)/"')
CNT = re.compile(r'region-item-count">\s*\+?([\d\s\u00a0]+)<')
SUM = re.compile(r'<span>([\d\s\u00a0]+)\s*₽')


def main():
    req = urllib.request.Request(URL, headers={'User-Agent': 'dumdv-site/1.0'})
    html = urllib.request.urlopen(req, timeout=60).read().decode('utf-8', 'replace')

    start = html.find('Топ поддержавших регионов')
    if start < 0:
        sys.exit('на странице нет блока «Топ поддержавших регионов» — вёрстка сайта изменилась')

    seen, rows, unknown = set(), [], []
    for m in ITEM.finditer(html[start:start + 400000]):
        block = m.group(1)
        c = CODE.search(block)
        if not c:
            continue
        code = int(c.group(1))
        if code in seen:
            continue
        seen.add(code)
        s = SUM.search(block)
        if not s:
            continue                      # прочерк вместо суммы — пожертвований не было
        total = int(re.sub(r'\D', '', s.group(1)))
        if total <= 0:
            continue
        if code not in NAMES:
            unknown.append(code)          # Крым, Севастополь — в карте их нет
            continue
        n = CNT.search(block)
        rows.append({'name': NAMES[code], 'sum': total,
                     'donors': int(re.sub(r'\D', '', n.group(1))) if n else None})

    if not rows:
        sys.exit('не разобрано ни одной строки — вёрстка сайта изменилась')
    rows.sort(key=lambda r: -r['sum'])

    today = __import__('datetime').date.today().isoformat()
    body = ['{', '  "period": %s,' % json.dumps(PERIOD, ensure_ascii=False),
            '  "updated": "%s",' % today, '  "regions": [']
    body.append(',\n'.join(
        '    { "name": %-44s "sum": %9d, "donors": %s }'
        % (json.dumps(r['name'], ensure_ascii=False) + ',', r['sum'],
           'null' if r['donors'] is None else r['donors'])
        for r in rows))
    body += ['  ]', '}', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(body))

    print('регионов с пожертвованиями: %d' % len(rows))
    if unknown:
        print('пропущено (нет в карте): коды %s' % ', '.join(map(str, unknown)))
    print('топ-3: %s' % ', '.join('%s %s ₽' % (r['name'], f"{r['sum']:,}".replace(',', ' '))
                                 for r in rows[:3]))
    print('записан %s' % OUT)


if __name__ == '__main__':
    main()
